def _subject_for(draft: str, title: str) -> str:
    """The first ``Subject:`` line's text, else the meeting title; never longer than 300."""
    match = _SUBJECT_LINE.search(draft)
    subject = match.group("subject").strip() if match else ""
    return (subject or title.strip())[:SUBJECT_MAX]


def _earliest(*moments: datetime | None) -> datetime | None:
    """The earliest of the recorded moments, ignoring the ones that never happened."""
    present = [moment for moment in moments if moment is not None]
    return min(present) if present else None


def _copy_problems(row: Any) -> list[str]:
    """Why ``row`` cannot be copied faithfully, as sentences. Empty when it can."""
    problems: list[str] = []
    status = row.status
    if row.owner_user_id is None:
        problems.append("the meeting has no owner_user_id, so the drafter is unknown")
    if row.followup_draft is None:
        problems.append("the follow-up has a status but no draft text")
    approver = row.followup_approved_by_user_id
    if status in {"APPROVED", "SENT"} and approver is None:
        problems.append(f"it is {status} but names no approver")
    if approver is not None and approver == row.owner_user_id:
        problems.append("its approver is the meeting owner, who is taken as the drafter")
    submitted_at = row.followup_submitted_at
    approved_at = row.followup_approved_at
    sent_at = row.followup_sent_at
    if status in {"DRAFTED", "OFFICER_REVIEW"} and (
        approver is not None or approved_at is not None
    ):
        problems.append(f"it is {status} but carries an approval")
    if status in {"APPROVED", "SENT"} and submitted_at is None:
        problems.append(f"it is {status} but records no submission time")
    if submitted_at is not None and approved_at is not None and submitted_at > approved_at:
        problems.append("its approval time is earlier than its submission time")
    if (status == "SENT") != (sent_at is not None):
        problems.append("its SENT status and its sent timestamp disagree")
    if sent_at is not None and approved_at is None:
        problems.append("it was sent but records no approval time")
    if sent_at is not None and approved_at is not None and approved_at > sent_at:
        problems.append("its sent time is earlier than its approval time")
    if (status == "DISCARDED") != (row.followup_discarded_at is not None):
        problems.append("its DISCARDED status and its discard timestamp disagree")
    return problems


def _copy_followups_out_of_meetings() -> int:
    """Copy every ``meetings.followup_*`` follow-up into ``meeting_followups``.

    Returns the number of rows copied. Validates every row before inserting any, so a
    refusal leaves nothing half-copied (and the migration transaction rolls back anyway).
    """
    bind = op.get_bind()
    rows = list(bind.execute(sa.text(_SELECT_OLD_FOLLOWUPS)))

    refusals = [
        f"meeting {row.meeting_id} ({row.title!r}): {'; '.join(problems)}"
        for row in rows
        if (problems := _copy_problems(row))
    ]
    if refusals:
        msg = (
            "Refusing to migrate meeting follow-ups that cannot be copied without guessing. "
            "Correct these rows (or run the documented demo reset for the synthetic demo "
            "database) and migrate again:\n  " + "\n  ".join(refusals)
        )
        raise RuntimeError(msg)

    insert = sa.text(_INSERT_FOLLOWUP)
    for row in rows:
        owner = row.owner_user_id
        status = row.status
        recipients = [row.organisation_name or MIGRATED_RECIPIENT_FALLBACK]
        submitted_at = row.followup_submitted_at
        sent_at = row.followup_sent_at
        discarded = status == "DISCARDED"
        drafted_at = (
            _earliest(submitted_at, row.followup_approved_at, sent_at, row.followup_discarded_at)
            or row.created_at
        )
        bind.execute(
            insert,
            {
                "id": uuid.UUID(bytes=ULID().bytes),
                "meeting_id": row.meeting_id,
                "status": status,
                "subject": _subject_for(row.followup_draft, row.title),
                "recipients": json.dumps(recipients, ensure_ascii=False),
                "body": row.followup_draft,
                "trace_id": row.followup_trace_id,
                "drafted_by_user_id": owner,
                "drafted_at": drafted_at,
                "submitted_by_user_id": owner if submitted_at is not None else None,
                "submitted_at": submitted_at,
                "approved_by_user_id": row.followup_approved_by_user_id,
                "approved_at": row.followup_approved_at,
                "sent_by_user_id": owner if sent_at is not None else None,
                "sent_at": sent_at,
                "discarded_by_user_id": owner if discarded else None,
                "discarded_at": row.followup_discarded_at,
                "discard_reason": MIGRATED_DISCARD_REASON if discarded else None,
                "classification": row.classification,
            },
        )
    return len(rows)


