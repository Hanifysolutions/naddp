    # Same reasoning as the ADR-0004 append-only triggers in the initial schema: a BEFORE
    # trigger binds every client -- the API, the seed, psql -- where an ORM guard binds only
    # the code that remembers it; and RAISE rather than RETURN NULL, because a silently
    # skipped DELETE reports success and changes nothing. TRUNCATE needs its own
    # statement-level trigger: a row-level trigger never fires for TRUNCATE.
    op.execute(
        f"""
        CREATE OR REPLACE FUNCTION {REJECT_DELETE_FUNCTION}()
        RETURNS TRIGGER
        LANGUAGE plpgsql
        AS $$
        BEGIN
            RAISE EXCEPTION
                'meeting_followups rows are never deleted: discarding a drafted diplomatic communication is itself an audited act (docs/OPEN_QUESTIONS.md Q-05). % is not permitted.',
                TG_OP
                USING ERRCODE = 'restrict_violation';
        END;
        $$
        """
    )
    op.execute(
        f"CREATE TRIGGER {NO_DELETE_TRIGGER} BEFORE DELETE ON {TABLE} "
        f"FOR EACH ROW EXECUTE FUNCTION {REJECT_DELETE_FUNCTION}()"
    )
    op.execute(
        f"CREATE TRIGGER {NO_TRUNCATE_TRIGGER} BEFORE TRUNCATE ON {TABLE} "
        f"FOR EACH STATEMENT EXECUTE FUNCTION {REJECT_DELETE_FUNCTION}()"
    )
    # The UPDATE guard. Order matters only for which sentence the caller reads first:
    # terminal immutability, provenance, the transition pairs, the content lock, and the
    # approval freeze.
    #
    # The pairs are app.domain.enums.FOLLOWUP_TRANSITIONS with the self-transition (edit)
    # left out, because a status that does not change is not a transition here. They are
    # written out rather than generated so the migration stays a fixed record of the DDL it
    # applied; tests/test_schema.py pins the behaviour of every refused shape.
    #
    # The content lock binds every update except DRAFTED to DRAFTED, so the statement that
    # leaves DRAFTED cannot rewrite the text on its way out. The approval freeze lets the
    # approval columns change only when both are set by OFFICER_REVIEW to APPROVED, or both
    # cleared by a return to DRAFTED -- which is what the service's _write_status and
    # _record_approver do, flushed as one UPDATE (the state write runs before the effects,
    # with no query between them). The CHECKs then refuse an approval left on a DRAFTED row.
    op.execute(
        f"""
        CREATE OR REPLACE FUNCTION {GUARD_UPDATE_FUNCTION}()
        RETURNS TRIGGER
        LANGUAGE plpgsql
        AS $$
        BEGIN
            IF OLD.status IN ('SENT', 'DISCARDED') THEN
                RAISE EXCEPTION
                    'meeting_followups row % is % and terminal: a sent or discarded follow-up is immutable (docs/OPEN_QUESTIONS.md Q-05)',
                    OLD.id, OLD.status
                    USING ERRCODE = 'restrict_violation';
            END IF;
            IF NEW.id IS DISTINCT FROM OLD.id
               OR NEW.meeting_id IS DISTINCT FROM OLD.meeting_id
               OR NEW.drafted_by_user_id IS DISTINCT FROM OLD.drafted_by_user_id
               OR NEW.drafted_at IS DISTINCT FROM OLD.drafted_at
               OR NEW.trace_id IS DISTINCT FROM OLD.trace_id
               OR NEW.supersedes_followup_id IS DISTINCT FROM OLD.supersedes_followup_id THEN
                RAISE EXCEPTION
                    'meeting_followups row %: id, meeting_id, drafted_by_user_id, drafted_at, trace_id and supersedes_followup_id are provenance and never change',
                    OLD.id
                    USING ERRCODE = 'restrict_violation';
            END IF;
            IF NEW.status IS DISTINCT FROM OLD.status
               AND (CAST(OLD.status AS text), CAST(NEW.status AS text)) NOT IN (
                   ('DRAFTED', 'OFFICER_REVIEW'),
                   ('DRAFTED', 'DISCARDED'),
                   ('OFFICER_REVIEW', 'APPROVED'),
                   ('OFFICER_REVIEW', 'DRAFTED'),
                   ('OFFICER_REVIEW', 'DISCARDED'),
                   ('APPROVED', 'SENT'),
                   ('APPROVED', 'DRAFTED'),
                   ('APPROVED', 'DISCARDED')
               ) THEN
                RAISE EXCEPTION
                    'meeting_followups row %: % to % is not a transition of the follow-up machine (docs/workflows.md section 2); SENT is reached only from APPROVED, and APPROVED only from OFFICER_REVIEW',
                    OLD.id, OLD.status, NEW.status
                    USING ERRCODE = 'restrict_violation';
            END IF;
            IF (OLD.status <> 'DRAFTED' OR NEW.status <> 'DRAFTED')
               AND (NEW.subject IS DISTINCT FROM OLD.subject
                    OR NEW.recipients IS DISTINCT FROM OLD.recipients
                    OR NEW.body IS DISTINCT FROM OLD.body) THEN
                RAISE EXCEPTION
                    'meeting_followups row % (% to %): subject, recipients and body are locked outside DRAFTED, including in the statement that leaves DRAFTED, because the artefact an approver sees is the artefact that gets sent',
                    OLD.id, OLD.status, NEW.status
                    USING ERRCODE = 'restrict_violation';
            END IF;
            IF (NEW.approved_by_user_id IS DISTINCT FROM OLD.approved_by_user_id
                OR NEW.approved_at IS DISTINCT FROM OLD.approved_at)
               AND NOT (OLD.status = 'OFFICER_REVIEW' AND NEW.status = 'APPROVED'
                        AND NEW.approved_by_user_id IS NOT NULL
                        AND NEW.approved_at IS NOT NULL)
               AND NOT (OLD.status <> 'DRAFTED' AND NEW.status = 'DRAFTED'
                        AND NEW.approved_by_user_id IS NULL
                        AND NEW.approved_at IS NULL) THEN
                RAISE EXCEPTION
                    'meeting_followups row % (% to %): the approval is frozen once given. approved_by_user_id and approved_at are set together only by approval (OFFICER_REVIEW to APPROVED) and cleared together only by a return to DRAFTED',
                    OLD.id, OLD.status, NEW.status
                    USING ERRCODE = 'restrict_violation';
            END IF;
            RETURN NEW;
        END;
        $$
        """
    )
    op.execute(
        f"CREATE TRIGGER {GUARD_UPDATE_TRIGGER} BEFORE UPDATE ON {TABLE} "
        f"FOR EACH ROW EXECUTE FUNCTION {GUARD_UPDATE_FUNCTION}()"
    )

    # -- Privileges ------------------------------------------------------------------
    #
    # The trigger protects against a bug; a missing privilege protects against intent.
    # infra/postgres/init/002_app_role.sql grants naddp_app DELETE on every new table by
    # default, so it is narrowed here. Unlike the append-only tables, UPDATE stays granted:
    # a follow-up legitimately moves through its states. The role check runs in Python for
    # the reason given in the initial schema migration.
    role_exists = bool(
        op.get_bind()
        .execute(sa.text("SELECT 1 FROM pg_roles WHERE rolname = 'naddp_app'"))
        .scalar()
    )
    op.execute(f"REVOKE DELETE, TRUNCATE ON {TABLE} FROM PUBLIC")
    if role_exists:
        op.execute(f"GRANT SELECT, INSERT, UPDATE ON {TABLE} TO naddp_app")
        op.execute(f"REVOKE DELETE, TRUNCATE ON {TABLE} FROM naddp_app")


